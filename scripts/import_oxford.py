"""Import every Oxford PDF entry without flattening part-of-speech/level pairs."""

import json
import re
from pathlib import Path

import pymupdf


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "The_Oxford_3000.pdf"
PARTS = r"(?:indefinite article|definite article|infinitive marker|modal v\.|auxiliary v\.|number|noun\.|n\.|v\.|adj\.|adv\.|prep\.|pron\.|det\.|conj\.|exclam\.)"
ENTRY = re.compile(rf"^(?P<word>.+?)\s+(?P<details>{PARTS}.*)$")
GROUP = re.compile(rf"(?P<pos>{PARTS}(?:\s*[,/]\s*{PARTS})*)\s*(?P<level>[AB][12])")


def extract():
    entries = []
    with pymupdf.open(SOURCE) as document:
        for page_number, page in enumerate(document, start=1):
            pending = []
            for raw in page.get_text().splitlines():
                line = " ".join(raw.split())
                if line.startswith(("© Oxford University Press", "The Oxford 3000")) or re.fullmatch(r"\d+ / \d+", line):
                    continue
                if not line:
                    continue
                pending.append(line)
                if not re.search(r"[AB][12]$", line):
                    continue
                text = " ".join(pending)
                match = ENTRY.fullmatch(text)
                if not match:
                    raise ValueError(f"Unknown entry on page {page_number}: {text}")
                groups = []
                end = 0
                for group in GROUP.finditer(match["details"]):
                    if match["details"][end:group.start()].strip(" ,"):
                        raise ValueError(f"Unparsed part of {text}")
                    groups.append({"pos": group["pos"], "level": group["level"]})
                    end = group.end()
                if not groups or match["details"][end:].strip():
                    raise ValueError(f"Incomplete levels in {text}")
                headword = match["word"]
                term = re.sub(r"\s*\(.*\)$", "", headword)
                term = re.sub(r"\d+$", "", term).replace("\u2019", "'")
                entries.append({
                    "word": headword,
                    "terms": ["a", "an"] if headword == "a, an" else [term],
                    "groups": groups,
                    "page": page_number,
                })
                pending.clear()
            if pending:
                raise ValueError(f"Unfinished entry on page {page_number}: {pending}")
    if len(entries) != 3000:
        raise ValueError(f"Unexpected entry count: {len(entries)}")
    if len({item["word"] for item in entries}) != len(entries):
        raise ValueError("Duplicate headwords need inspection")
    return entries


if __name__ == "__main__":
    entries = extract()
    output = "// Generated by scripts/import_oxford.py from The_Oxford_3000.pdf.\n"
    output += "window.OXFORD_WORDS = " + json.dumps(entries, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "oxford-words.js").write_text(output, encoding="utf-8")
    print(f"Imported {len(entries)} entries; {sum(len(item['groups']) for item in entries)} POS/level groups.")
