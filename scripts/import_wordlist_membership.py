"""Generate source-list membership flags for the merged vocabulary."""

import json

from import_longman import normalize
from import_oxford import ROOT, extract as extract_oxford
from select_words import extract_words


def build_membership(oxford, longman):
    oxford_terms = {normalize(term) for entry in oxford for term in entry["terms"]}
    longman_terms = {normalize(entry["word"]) for entry in longman}
    entries = [*oxford, *[
        {"word": entry["word"], "terms": [entry["word"]]}
        for entry in longman if normalize(entry["word"]) not in oxford_terms
    ]]
    membership = {}
    for entry in entries:
        terms = {normalize(term) for term in entry["terms"]}
        membership[entry["word"]] = {
            "oxford": bool(terms & oxford_terms),
            "longman": bool(terms & longman_terms),
        }
    return membership


if __name__ == "__main__":
    oxford = extract_oxford()
    longman = extract_words()
    if len(longman) != 3160:
        raise ValueError(f"Unexpected Longman headword count: {len(longman)}")
    membership = build_membership(oxford, longman)
    if len(membership) != 3578 or any(not membership[entry["word"]]["oxford"] for entry in oxford):
        raise ValueError(f"Unexpected vocabulary membership count: {len(membership)}")
    output = "// Generated by scripts/import_wordlist_membership.py from both source PDFs.\n"
    output += "window.WORDLIST_MEMBERSHIP = " + json.dumps(
        membership, ensure_ascii=False, separators=(",", ":")
    ) + ";\n"
    (ROOT / "wordlist-membership.js").write_text(output, encoding="utf-8")
    print(f"Generated membership flags for {len(membership)} vocabulary entries.")
    print(f"Oxford: {sum(item['oxford'] for item in membership.values())}; "
          f"Longman: {sum(item['longman'] for item in membership.values())}; "
          f"both: {sum(item['oxford'] and item['longman'] for item in membership.values())}.")
